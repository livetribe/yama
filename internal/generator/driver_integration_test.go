// The specs in this file start Google Wire. Every other test in the tree gives
// the run an output that takes the place of Google Wire's own. Such an
// output states nothing about whether Google Wire accepts what the run
// derives.

// requireGo skips the test when the machine has no Go toolchain.
func requireGo(t *testing.T) {
	t.Helper()

	if _, err := exec.LookPath("go"); err != nil {
		t.Skipf("go toolchain not found on PATH: %v", err)
	}
}

// quietDriver returns a Driver that writes what it did nowhere. A test that
// reads that output back assigns progress a buffer of its own instead.
func quietDriver(dir string, patterns []string, args wire.Args) *Driver {
	d := NewDriver(dir, patterns, args)
	d.progress = io.Discard

	return d
}

// A fixture is one package under testdata, named with the files that it holds.
type fixture struct {
	name  string
	files []string
}

var (
	// wirerun holds a plain graph. NewDB returns a cleanup and declares no
	// capability, and App consumes it.
	wirerun = fixture{"wirerun", []string{"components.go", "lifecycle.go"}}

	// taggedrun holds the same graph, with the one provider of *DB behind the
	// special build tag.
	taggedrun = fixture{"taggedrun", []string{"components.go", "special.go", "lifecycle.go"}}

	// badgraph holds a stub that names no provider of *DB. Google Wire rejects
	// that stub.
	badgraph = fixture{"badgraph", []string{"components.go", "lifecycle.go"}}

	// badstub holds a stub that declares two results. A lifecycle stub declares
	// three.
	badstub = fixture{"badstub", []string{"components.go", "lifecycle.go"}}

	// valuerun holds a stub with a graph that takes a wire.Value provider.
	valuerun = fixture{"valuerun", []string{"components.go", "lifecycle.go"}}

	// setrun holds a stub that names a provider set, and never the package that
	// declares the provider in that set. testdata/setlib states the set, and
	// testdata/setother declares the provider.
	setrun = fixture{"setrun", []string{"components.go", "lifecycle.go"}}
)

// copyFixture puts a copy of the fixture package in a directory of its own. It
// returns the path of that copy.
//
// The copy is under testdata, inside this module. Google Wire resolves its own
// import and the yama import against the module of the directory that it runs
// in. No directory outside this module holds either one.
func copyFixture(t *testing.T, f fixture) string {
	t.Helper()

	root, err := filepath.Abs("testdata")
	require.NoError(t, err)

	source := filepath.Join(root, f.name)

	dir, err := os.MkdirTemp(root, "run-")
	require.NoError(t, err)

	t.Cleanup(func() {
		_ = os.RemoveAll(dir)
	})

	for _, name := range f.files {
		content, readErr := os.ReadFile(filepath.Join(source, name))
		require.NoError(t, readErr)

		//nolint:gosec // name is a constant of this file, and dir is the directory that MkdirTemp just made.
		require.NoError(t, os.WriteFile(filepath.Join(dir, name), content, 0o600))
	}

	return dir
}

// TestDriverRunsGoogleWire runs one whole generation over a real package. It is
// the one test that proves Google Wire accepts the injector that wire.Derive
// wrote.
func TestDriverRunsGoogleWire(t *testing.T) {
	requireGo(t)

	dir := copyFixture(t, wirerun)
	t.Chdir(dir)

	d := quietDriver(".", []string{"."}, wire.Args{})

	require.NoError(t, d.Run(context.Background()))

	content, err := os.ReadFile("lifecycle_gen.go")
	require.NoError(t, err)

	lifecycle := string(content)

	assert.Contains(t, lifecycle, "// Code generated by Yama. DO NOT EDIT.")
	signature := "func NewAppLifecycle(ctx context.Context, node *yaml.Node, opts ...yama.Option) " +
		"(*App, yama.Lifecycle, error)"

	assert.Contains(t, lifecycle, signature)
	assert.Contains(t, lifecycle, "rt.NewLifecycleBuilder(opts...)")
}

