// TestDriverGeneratesPastAPackageItCannotWriteTo drives a run over a family
// with one directory that takes no new file. That package fails. Every other
// package still takes its lifecycle file, and the failure reaches the caller.
func TestDriverGeneratesPastAPackageItCannotWriteTo(t *testing.T) {
	requireGo(t)

	if runtime.GOOS == "windows" {
		t.Skip("Windows does not apply the permission bits of a directory, so the failure cannot be staged")
	}

	if os.Geteuid() == 0 {
		t.Skip("the superuser writes to a read-only directory, so the failure cannot be staged")
	}

	dir := copyFamily(t, "multipkg")
	readOnly := filepath.Join(dir, "a")

	require.NoError(t, os.Chmod(readOnly, 0o500))

	t.Cleanup(func() {
		_ = os.Chmod(readOnly, 0o700)
	})

	t.Chdir(dir)

	d := quietDriver(".", []string{"./..."}, wire.Args{})

	require.Error(t, d.Run(context.Background()))

	assert.NoFileExists(t, filepath.Join(readOnly, "lifecycle_gen.go"))
	assert.FileExists(t, filepath.Join(dir, "b", "lifecycle_gen.go"))
}

// TestDriverReportsWireAgainstTheStubTheUserWrote drives a run over a package
// that Google Wire rejects. It reads what the run printed.
//
// Google Wire reads the file that Yama derived, and it names the injector that
// Yama invented. The user wrote neither one, and neither one survives the run.
func TestDriverReportsWireAgainstTheStubTheUserWrote(t *testing.T) {
	requireGo(t)

	dir := copyFixture(t, badgraph)
	t.Chdir(dir)

	var progress bytes.Buffer

	d := NewDriver(".", []string{"."}, wire.Args{})
	d.progress = &progress

	require.Error(t, d.Run(context.Background()))

	reported := progress.String()

	assert.Contains(t, reported, "lifecycle.go:", "names the stub file")
	assert.Contains(t, reported, "inject NewAppLifecycle", "names the stub")
	assert.NotContains(t, reported, wire.DerivedFileName, "names no transient file")
	assert.NotContains(t, reported, "inject yama_", "names no derived injector")
}

